-- AJUSTE AL DIA EN QUE SE CORRE EL SCRIPT
-- Los datos se generaron tomando el 30/07/2026 como "hoy". Si el script se
-- ejecuta antes de esa fecha, estas tres sentencias devuelven a 'en espera'
-- las reservas que todavia no ocurrieron y les sacan el consumo, para que no
-- queden consumos con fecha futura.
-- ============================================================
DELETE cd FROM consumo_detalle cd
  JOIN consumos co ON co.id = cd.consumo_id
  JOIN reservas r  ON r.id = co.reserva_id
  WHERE r.fecha >= CURDATE();

DELETE co FROM consumos co
  JOIN reservas r ON r.id = co.reserva_id
  WHERE r.fecha >= CURDATE();

UPDATE reservas SET estado_asistencia = 'en_espera' WHERE fecha >= CURDATE();

